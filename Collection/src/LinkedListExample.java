import java.util.LinkedList;

public class LinkedListExample {

		public static void main(String[] args) {
			
			LinkedList l ;
			l=new LinkedList();
			l.addFirst(10);
			System.out.println(l);
		l.addLast(900.0);
		System.out.println(l.getFirst());
		l.getLast();
		l.removeFirst();
		l.removeLast();
		System.out.println(l);

	}

	
}
